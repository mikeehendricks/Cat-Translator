/* Build the recogniser's reference fingerprints and write src/templates.js */
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { performance } from 'node:perf_hooks';

const root = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
for (const f of ['src/lexicon.js', 'src/tokens.js', 'src/engine.js', 'src/synth.js', 'src/match.js']) {
  vm.runInThisContext(fs.readFileSync(path.join(root, f), 'utf8'), { filename: f });
}
const { MEOW_GROUPS: GRP, MEOW_CANON: CANON, MEOW_ENGINE: E, MEOW_MATCH: M, MEOW_SYNTH: S } = globalThis;

/* The recogniser hears ONE meow at a time (recordings are segmented first), so
   every reference is a single token. Repeated count-meows land here once and
   the decoder turns a run of them back into a number. */
const seqs = [];
const seenTok = new Set();
for (const gr of GRP) {
  const toks = gr.seq.split(' ');
  if (toks.length !== 1) continue;
  if (seenTok.has(toks[0])) continue;
  seenTok.add(toks[0]);
  seqs.push({ tokens: toks, text: gr.canon, kind: gr.kind });
}
seqs.sort((a, b) => a.text < b.text ? -1 : 1);
console.log(`building templates for ${seqs.length} distinct meows ...`);
const SR = 22050;
const t0 = performance.now();
const templates = M.buildTemplates(seqs, (descs, opts) => S.renderUtterance(descs, opts), { sr: SR });
const t1 = performance.now();
console.log(`  ${templates.items.length} fingerprints over ${templates.stats.classes} classes in ${((t1 - t0) / 1000).toFixed(1)}s  (typicalDist ${templates.stats.typicalDist.toFixed(2)})`);

const payload = {
  sr: SR,
  features: M.FEATURES,
  weights: templates.stats.weights,
  mean: Array.from(templates.stats.mean),
  std: Array.from(templates.stats.std),
  overallStd: Array.from(templates.stats.overallStd),
  typicalDist: templates.stats.typicalDist,
  classes: templates.classes.map(c => ({
    t: c.tokens, n: c.n,
    m: Array.from(c.mean, v => Math.round(v * 1000) / 1000),
    v: Array.from(c.var, v => Math.round(v * 1e6) / 1e6),
  })),
  items: templates.items.map(it => ({
    t: it.tokens, x: it.text, v: it.variant, d: Array.from(it.feat, (v) => Math.round(v * 1000) / 1000),
  })),
};
const out = path.join(root, 'src/templates.js');
fs.writeFileSync(out,
  '/* generated by tools/build-templates.mjs - reference meow fingerprints. do not edit. */\n' +
  'globalThis.MEOW_TEMPLATES = ' + JSON.stringify(payload) + ';\n');
console.log(`wrote ${path.relative(root, out)} (${(fs.statSync(out).size / 1024).toFixed(0)} kB)`);
